import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('mensajería completa: migraciones repetibles, aislamiento, acciones, búsqueda y adjuntos',async()=>{
 const db=new PGlite();
 const a='00000000-0000-4000-8000-000000000001',b='00000000-0000-4000-8000-000000000002',c='00000000-0000-4000-8000-000000000003';
 const token=n=>`10000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;create schema storage;
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   grant usage on schema auth,storage to authenticated;
   create table asis_perfiles(id uuid primary key,nombre text,activo boolean,rol text);
   insert into asis_perfiles values('${a}','Ana',true,'colaborador'),('${b}','Beto',true,'colaborador'),('${c}','Admin',true,'direccion');
   create table storage.objects(bucket_id text,name text,metadata jsonb);
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   alter table storage.objects enable row level security;
   grant select,insert on storage.objects to authenticated;`);
  for(const file of ['chat_01_mensajes.sql','chat_06_realtime_eventos.sql','chat_07_imagenes.sql','chat_10_grupos.sql','chat_11_coordinaciones.sql','chat_12_grupos_privados.sql']){
   const sql=await fs.readFile(new URL('../supabase/'+file,import.meta.url),'utf8');await db.exec(sql);await db.exec(sql);
  }
  const login=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated')};
  const query=async(sql,params=[]) => (await db.query(sql,params)).rows;
  const send=async(text,n,to=b,reply=null,group=null,path=null,name=null)=>(await query('select chat_v2_enviar($1,$2,$3,$4,$5,$6,$7) as m',[token(n),text,to,group,reply,path,name]))[0].m;
  const action=async(id,kind,text=null,group=false)=>(await query('select chat_v2_accion($1,$2,$3,$4) as m',[group,id,kind,text]))[0].m;
  await login(a);
  assert.equal((await query('select chat_capacidades() as c'))[0].c.version,2);
  const first=await send('Coordinar reunión',1);assert.equal((await send('Coordinar reunión',1)).id,first.id);
  await assert.rejects(send('Distinto',1),/otro mensaje/);
  const reply=await send('De acuerdo',2,b,first.id);assert.equal(reply.respuesta.contenido,'Coordinar reunión');
  const other=await send('Solo con Admin',3,c);
  await assert.rejects(send('Cruzar conversación',4,b,other.id),/responder/);
  await login(c);
  await assert.rejects(action(first.id,'editar','Intrusión'),/no disponible/);
  await assert.rejects(action(first.id,'reaccionar','👍'),/no disponible/);
  assert.equal((await query('select * from chat_v2_historial($1)',[b])).length,0);
  await login(b);
  await assert.rejects(action(first.id,'editar','No soy autor'),/Solo puedes/);
  assert.equal((await action(first.id,'reaccionar','👍')).reacciones[0].total,1);
  await assert.rejects(action(first.id,'reaccionar','<script>'),/check constraint/);
  await login(a);
  assert.equal((await action(first.id,'editar','Reunión a las 10')).contenido,'Reunión a las 10');
  assert.equal((await query('select * from chat_v2_historial($1,null,null,$2)',[b,'REUNIÓN'])).length,1);
  assert.equal((await query('select * from chat_v2_historial($1,null,null,$2)',[b,'%'])).length,0);
  const path=a+'/'+token(5);
  await query("insert into storage.objects values('chat-archivos',$1,$2)",[path,{mimetype:'application/pdf',size:1200}]);
  const attached=await send('',5,b,null,null,path,'Agenda.pdf');
  assert.equal(attached.archivo_mime,'application/pdf');
  assert.equal((await query('select * from storage.objects')).length,1);
  await login(c);assert.equal((await query('select * from storage.objects')).length,0);
  await login(b);assert.equal((await query('select * from storage.objects')).length,1);
  await login(a);await action(attached.id,'eliminar');
  assert.equal((await query('select * from storage.objects')).length,0);
  await assert.rejects(send('',6,b,null,null,a+'/'+token(6),'Falta.pdf'),/no se ha subido/);
  await action(first.id,'eliminar');
  const after=(await query('select * from chat_v2_historial($1)',[b])).map(x=>Object.values(x)[0]);
  assert.equal(after.find(m=>m.id===reply.id).respuesta.contenido,'Mensaje eliminado');
  assert.deepEqual(after.find(m=>m.id===first.id).reacciones,[]);
  await assert.rejects(action(first.id,'editar','Restaurar'),/eliminado/);
  // Grupos: no hay acceso al historial ni a sus archivos sin pertenencia.
  const group=(await query('select * from chat_grupos()'))[0].id;
  await query('select chat_grupo_unirse($1)',[group]);
  const gm=await send('Mensaje al grupo',7,null,null,group);
  await login(c);await assert.rejects(query('select * from chat_v2_historial(null,$1)',[group]),/perteneces/);
  await assert.rejects(action(gm.id,'reaccionar','👍',true),/no disponible/);
  await login(b);await query('select chat_grupo_unirse($1)',[group]);
  const gr=await send('Respuesta de grupo',8,null,gm.id,group);
  assert.equal(gr.respuesta.contenido,'Mensaje al grupo');
  await action(gm.id,'reaccionar','❤️',true);
  await query('select chat_grupo_salir($1)',[group]);
  await assert.rejects(action(gm.id,'reaccionar','👍',true),/no disponible/);
  await assert.rejects(query('select * from chat_reacciones'),/permission denied/);
  await login(a);
  const privateGroup=(await query('select chat_grupo_crear($1,$2) as id',['Coordinaciones privadas',[b]]))[0].id;
  assert.equal((await query('select chat_grupo_detalle($1) as g',[privateGroup]))[0].g.miembros.length,2);
  await login(c);
  assert.ok(!(await query('select * from chat_grupos()')).some(g=>g.id===privateGroup));
  await assert.rejects(query('select chat_grupo_unirse($1)',[privateGroup]),/privado/);
  await assert.rejects(query("select chat_grupo_administrar($1,'agregar',$2)",[privateGroup,c]),/Solo quien/);
  await login(a);
  await assert.rejects(query('select chat_grupo_salir($1)',[privateGroup]),/Transfiere/);
  await query("select chat_grupo_administrar($1,'agregar',$2)",[privateGroup,c]);
  await query("select chat_grupo_administrar($1,'quitar',$2)",[privateGroup,c]);
  await login(c);await assert.rejects(query('select chat_grupo_detalle($1)',[privateGroup]),/perteneces/);
  await login(a);await query("select chat_grupo_administrar($1,'transferir',$2)",[privateGroup,b]);
  await query('select chat_grupo_salir($1)',[privateGroup]);
  await assert.rejects(query('select chat_grupo_detalle($1)',[privateGroup]),/perteneces/);
  await db.exec('reset role');await db.query('update asis_perfiles set activo=false where id=$1',[a]);await login(a);
  await assert.rejects(query('select chat_capacidades()'),/no tiene acceso/);
 }finally{await db.close()}
});
